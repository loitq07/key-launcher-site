module.exports = function handler(request, response) {
    // Country-dependent responses must never be shared between visitors by any cache.
    response.setHeader('Cache-Control', 'private, no-store');
    response.setHeader('CDN-Cache-Control', 'no-store');
    response.setHeader('Vercel-CDN-Cache-Control', 'no-store');
    response.setHeader('Content-Type', 'application/json; charset=utf-8');
    response.setHeader('X-Content-Type-Options', 'nosniff');

    if (request.method !== 'GET' && request.method !== 'HEAD') {
        response.setHeader('Allow', 'GET, HEAD');
        response.statusCode = 405;
        return response.end(JSON.stringify({ error: 'Method not allowed' }));
    }

    // Trust only Vercel's IP geolocation, never a query, cookie, browser locale, or request body.
    // https://vercel.com/docs/headers/request-headers#x-vercel-ip-country
    const country = request.headers['x-vercel-ip-country'];
    const prices = typeof country === 'string' && /^[A-Z]{2}$/.test(country) &&
        Object.hasOwn(REGIONAL_PRICES, country) ? REGIONAL_PRICES[country] : null;

    response.statusCode = 200;
    return response.end(request.method === 'HEAD' ? undefined : JSON.stringify(prices));
};
